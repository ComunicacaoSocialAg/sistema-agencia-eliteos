import { useState, useRef, useEffect } from 'react';
import { Bot, Sparkles, Send, FileText, PenTool, BarChart, Rocket, Check, Plus, AlertCircle, Loader2 } from 'lucide-react';
import { cn } from '../utils/cn';
import { chatWithAgent, isGeminiConfigured, isAIConfigured } from '../lib/gemini';
import { useTasks } from '../hooks/useTasks';

const AGENTS = [
  { id: 'brief', name: 'Assistente de Briefing', icon: FileText, desc: 'Gera briefs completos a partir de textos curtos do cliente.' },
  { id: 'content', name: 'Gerador de Conteúdo', icon: PenTool, desc: 'Cria copies, legendas e roteiros baseados na brand persona.' },
  { id: 'analyst', name: 'Analista de Desempenho', icon: BarChart, desc: 'Interpreta dados do Reportei/Meta e sugere otimizações.' },
  { id: 'campaign', name: 'Gerador de Campanhas', icon: Rocket, desc: 'Cria um fluxo completo de tarefas para uma campanha no Kanban.' },
];

function MessageBubble({ msg, onAddTasksToKanban }) {
  if (msg.role === 'user') {
    return (
      <div className="flex gap-4 max-w-3xl mx-auto flex-row-reverse">
        <div className="w-8 h-8 rounded-full bg-gradient-to-tr from-cs-primary to-cs-accent flex items-center justify-center shrink-0 border-2 border-cs-bg text-white font-bold text-xs">B</div>
        <div className="bg-cs-primary text-white rounded-2xl rounded-tr-sm p-4 text-sm max-w-xl">{msg.text}</div>
      </div>
    );
  }

  if (msg.role === 'loading') {
    return (
      <div className="flex gap-4 max-w-3xl mx-auto">
        <div className="w-8 h-8 rounded-full bg-cs-accent flex items-center justify-center shrink-0">
          <Bot size={16} className="text-white" />
        </div>
        <div className="bg-cs-surface border border-cs-border rounded-2xl rounded-tl-sm px-4 py-3 flex items-center gap-2">
          <Loader2 size={16} className="text-cs-accent animate-spin" />
          <span className="text-cs-text-secondary text-sm">Pensando...</span>
        </div>
      </div>
    );
  }

  return (
    <div className="flex gap-4 max-w-3xl mx-auto">
      <div className="w-8 h-8 rounded-full bg-cs-accent flex items-center justify-center shrink-0">
        <Bot size={16} className="text-white" />
      </div>
      <div className="flex-1 space-y-3">
        {msg.text && (
          <div className="bg-cs-surface border border-cs-border rounded-2xl rounded-tl-sm p-4 text-sm text-cs-text-primary whitespace-pre-wrap leading-relaxed">
            {msg.text}
          </div>
        )}

        {/* Kanban tasks generated by Campaign agent */}
        {msg.tasks && msg.tasks.length > 0 && (
          <div className="bg-cs-surface border border-cs-accent/20 rounded-xl overflow-hidden">
            <div className="p-4 border-b border-cs-border">
              <div className="text-xs font-bold text-cs-accent mb-0.5">Fluxo de Tarefas Gerado</div>
              <p className="text-xs text-cs-text-secondary">Clique em "Enviar ao Kanban" para adicionar ao seu quadro de Produção.</p>
            </div>
            <div className="divide-y divide-cs-border">
              {msg.tasks.map((task, i) => (
                <div key={i} className="flex items-center gap-3 px-4 py-3">
                  <Check size={14} className="text-green-500 shrink-0" />
                  <div className="flex-1 min-w-0">
                    <div className="text-sm text-white font-medium truncate">{task.title}</div>
                    <div className="text-[10px] text-cs-text-secondary">{task.assigned_to} • {task.deadline} • {task.tag}</div>
                  </div>
                </div>
              ))}
            </div>
            <div className="p-3 border-t border-cs-border">
              <button
                onClick={() => onAddTasksToKanban(msg.tasks)}
                className="w-full bg-cs-primary hover:bg-cs-primary-hover text-white py-2 rounded-lg text-sm font-medium transition-colors flex items-center justify-center gap-2"
              >
                <Plus size={15} /> Enviar {msg.tasks.length} tarefas ao Kanban
              </button>
            </div>
          </div>
        )}
      </div>
    </div>
  );
}

export default function AILayerView() {
  const [activeAgent, setActiveAgent] = useState('content');
  const [conversations, setConversations] = useState(() => {
    try {
      const saved = localStorage.getItem('csag_ai_history');
      return saved ? JSON.parse(saved) : {};
    } catch {
      return {};
    }
  });
  const [provider, setProvider] = useState('auto');
  const [inputMessage, setInputMessage] = useState('');
  const [isLoading, setIsLoading] = useState(false);
  const messagesEndRef = useRef(null);
  const { createTask } = useTasks();

  const messages = conversations[activeAgent] || [];
  const selectedAgent = AGENTS.find(a => a.id === activeAgent);

  useEffect(() => {
    messagesEndRef.current?.scrollIntoView({ behavior: 'smooth' });
  }, [messages]);

  useEffect(() => {
    localStorage.setItem('csag_ai_history', JSON.stringify(conversations));
  }, [conversations]);

  const handleSend = async () => {
    const text = inputMessage.trim();
    if (!text || isLoading) return;

    const userMsg = { role: 'user', text };
    const loadingMsg = { role: 'loading' };

    setConversations(prev => ({
      ...prev,
      [activeAgent]: [...(prev[activeAgent] || []), userMsg, loadingMsg],
    }));
    setInputMessage('');
    setIsLoading(true);

    try {
      const history = (conversations[activeAgent] || []).filter(m => m.role !== 'loading');
      const response = await chatWithAgent(activeAgent, history, text, provider);

      const aiMsg = {
        role: 'ai',
        text: response.text || '',
        tasks: response.tasks || null,
      };

      setConversations(prev => {
        const current = prev[activeAgent] || [];
        // Replace loading message with real response
        const withoutLoading = current.filter(m => m.role !== 'loading');
        return { ...prev, [activeAgent]: [...withoutLoading, aiMsg] };
      });
    } catch (error) {
      const errMsg = { role: 'ai', text: `❌ Erro: ${error.message}` };
      setConversations(prev => {
        const current = prev[activeAgent] || [];
        const withoutLoading = current.filter(m => m.role !== 'loading');
        return { ...prev, [activeAgent]: [...withoutLoading, errMsg] };
      });
    } finally {
      setIsLoading(false);
    }
  };

  const handleAddTasksToKanban = async (tasks) => {
    for (const task of tasks) {
      await createTask({
        title: task.title,
        assigned_to: task.assigned_to,
        status: task.status || 'backlog',
        deadline: task.deadline,
        tag: task.tag,
      });
    }
    // Confirm feedback
    setConversations(prev => ({
      ...prev,
      [activeAgent]: [...(prev[activeAgent] || []), {
        role: 'ai',
        text: `✅ ${tasks.length} tarefas adicionadas ao Kanban com sucesso! Acesse o módulo de Produção para visualizá-las.`,
      }],
    }));
  };

  const handleKeyDown = (e) => {
    if (e.key === 'Enter' && !e.shiftKey) {
      e.preventDefault();
      handleSend();
    }
  };

  return (
    <div className="h-full flex bg-cs-bg">
      {/* Agents Sidebar */}
      <div className="w-80 border-r border-cs-border bg-cs-surface/50 p-6 flex flex-col">
        <div className="mb-6">
          <h2 className="text-xl font-bold text-white flex items-center gap-2 mb-1">
            <Bot size={24} className="text-cs-accent" />
            Camada de IA
          </h2>
          <p className="text-xs text-cs-text-secondary">Gemini + ChatGPT Integrados</p>
        </div>

        {!isAIConfigured && (
          <div className="bg-yellow-500/10 border border-yellow-500/30 rounded-xl p-3 mb-4">
            <div className="flex items-start gap-2">
              <AlertCircle size={14} className="text-yellow-500 mt-0.5 shrink-0" />
              <p className="text-xs text-yellow-400">
                Nenhuma IA configurada. Configure <code className="bg-black/20 px-1 rounded">GEMINI_API_KEY</code> ou <code className="bg-black/20 px-1 rounded">OPENAI_API_KEY</code> via <code className="bg-black/20 px-1 rounded">supabase secrets set</code> (servidor, não .env do frontend)
              </p>
            </div>
          </div>
        )}

        <div className="flex-1 space-y-3 overflow-y-auto custom-scrollbar">
          <div className="text-xs font-semibold text-cs-text-secondary uppercase tracking-wider mb-3">Seus Agentes</div>
          {AGENTS.map(agent => (
            <button
              key={agent.id}
              onClick={() => setActiveAgent(agent.id)}
              className={cn(
                "w-full text-left p-4 rounded-xl border transition-all",
                activeAgent === agent.id
                  ? 'bg-cs-accent/10 border-cs-accent shadow-[0_0_15px_rgba(139,92,246,0.15)]'
                  : 'bg-cs-bg border-cs-border hover:border-cs-accent/50'
              )}
            >
              <div className="flex items-center gap-3 mb-2">
                <div className={cn("p-2 rounded-lg", activeAgent === agent.id ? 'bg-cs-accent text-white' : 'bg-cs-surface text-cs-text-secondary')}>
                  <agent.icon size={16} />
                </div>
                <span className={cn("font-semibold text-sm", activeAgent === agent.id ? 'text-white' : 'text-cs-text-primary')}>
                  {agent.name}
                </span>
              </div>
              <p className="text-xs text-cs-text-secondary leading-relaxed">{agent.desc}</p>
            </button>
          ))}
        </div>
      </div>

      {/* Chat Area */}
      <div className="flex-1 flex flex-col relative overflow-hidden">
        {/* Header */}
        <div className="h-16 border-b border-cs-border bg-cs-bg/90 backdrop-blur flex items-center px-8 z-10 shrink-0">
          <div className="flex items-center gap-3">
            <div className="p-1.5 bg-cs-accent/20 text-cs-accent rounded-md">
              <selectedAgent.icon size={18} />
            </div>
            <div>
              <h3 className="text-white font-medium text-sm">{selectedAgent.name}</h3>
              <p className="text-xs text-cs-text-secondary flex items-center gap-1">
                <span className={cn("w-1.5 h-1.5 rounded-full inline-block", isAIConfigured ? "bg-green-500" : "bg-yellow-500")}></span>
                {isAIConfigured ? (isGeminiConfigured ? 'Gemini + GPT • Ativo' : 'GPT-4o-mini • Ativo') : 'IA não configurada'}
              </p>
            </div>
          </div>
            <div className="ml-auto flex items-center gap-3">
              <select
                value={provider}
                onChange={e => setProvider(e.target.value)}
                className="text-xs bg-cs-bg text-cs-text-secondary border border-cs-border rounded-lg px-2 py-1.5 focus:outline-none focus:border-cs-accent transition-colors"
              >
                <option value="auto">Auto (Gemini → GPT)</option>
                <option value="gemini">Forçar Gemini</option>
                <option value="gpt">Forçar ChatGPT</option>
              </select>
              <button
                onClick={() => setConversations(prev => ({ ...prev, [activeAgent]: [] }))}
                className="text-xs text-cs-text-secondary hover:text-white border border-cs-border px-3 py-1.5 rounded-lg hover:bg-cs-surface transition-colors"
              >
                Nova conversa
              </button>
            </div>
        </div>

        {/* Chat history */}
        <div className="flex-1 overflow-y-auto p-8 space-y-6 custom-scrollbar">
          {/* Welcome */}
          <div className="flex gap-4 max-w-3xl mx-auto">
            <div className="w-8 h-8 rounded-full bg-cs-accent flex items-center justify-center shrink-0">
              <Bot size={16} className="text-white" />
            </div>
            <div className="bg-cs-surface border border-cs-border rounded-2xl rounded-tl-sm p-4 text-sm text-cs-text-primary">
              Olá! Sou o <strong className="text-white">{selectedAgent.name}</strong>. Como posso otimizar o fluxo da Comunicação Social Ag hoje?
              {!isAIConfigured && (
                <p className="mt-2 text-yellow-400 text-xs">⚠️ Configure pelo menos uma chave de IA no arquivo <code>.env</code> para ativar as respostas.</p>
              )}
            </div>
          </div>

          {messages.map((msg, i) => (
            <MessageBubble key={i} msg={msg} onAddTasksToKanban={handleAddTasksToKanban} />
          ))}

          <div ref={messagesEndRef} />
        </div>

        {/* Input Area */}
        <div className="p-6 bg-cs-bg border-t border-cs-border shrink-0">
          <div className="max-w-3xl mx-auto relative">
            <textarea
              value={inputMessage}
              onChange={(e) => setInputMessage(e.target.value)}
              onKeyDown={handleKeyDown}
              placeholder={`Comandar o ${selectedAgent.name}... (Enter para enviar)`}
              className="w-full bg-cs-surface border border-cs-border rounded-xl pl-4 pr-14 py-4 text-sm text-white focus:outline-none focus:border-cs-accent focus:ring-1 focus:ring-cs-accent resize-none overflow-hidden"
              rows="2"
              disabled={isLoading}
            />
            <button
              onClick={handleSend}
              disabled={isLoading || !inputMessage.trim()}
              className="absolute right-3 bottom-3 p-2 bg-cs-accent hover:bg-purple-600 disabled:opacity-50 disabled:cursor-not-allowed text-white rounded-lg transition-colors flex items-center justify-center shadow-lg shadow-purple-500/20"
            >
              {isLoading ? <Loader2 size={16} className="animate-spin" /> : <Send size={16} />}
            </button>
          </div>
          <div className="max-w-3xl mx-auto mt-2 flex items-center justify-center gap-2 text-[10px] text-cs-text-secondary">
            <Sparkles size={10} className="text-cs-accent" />
            Powered by Gemini (Google) + ChatGPT (OpenAI) — Fallback automático. Enter para enviar, Shift+Enter para nova linha.
          </div>
        </div>
      </div>
    </div>
  );
}
